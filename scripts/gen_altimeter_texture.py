def render(rows):
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), rows
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != ".":
                img.putpixel((x, y), PALETTE[ch] + (255,))
    return img


def main():
    chosen = "A"
    if "--variant" in sys.argv:
        chosen = sys.argv[sys.argv.index("--variant") + 1].upper()
    if chosen not in VARIANTS:
        sys.exit(f"нет варианта {chosen}, есть: {', '.join(VARIANTS)}")

    out_dir = os.path.join(DOCS, "altimeters")
    os.makedirs(out_dir, exist_ok=True)
    scale, pad, label = 8, 8, 14
    cell = 16 * scale + pad
    sheet = Image.new("RGBA", (pad + cell * len(VARIANTS), pad + label + 16 * scale + pad), (139, 139, 139, 255))
    draw = ImageDraw.Draw(sheet)
    for i, (name, rows) in enumerate(VARIANTS.items()):
        img = render(rows)
        img.save(os.path.join(out_dir, f"{name}.png"))
        if name == chosen:
            img.save(ITEM)
        x = pad + i * cell
        draw.text((x + 16 * scale // 2 - 3, pad // 2), name, fill=(255, 255, 255, 255))
        sheet.alpha_composite(img.resize((16 * scale, 16 * scale), Image.NEAREST), (x, pad + label))
    sheet.save(os.path.join(DOCS, "altimeters.png"))
    print("вариант", chosen, "->", ITEM)


if __name__ == "__main__":
    main()
